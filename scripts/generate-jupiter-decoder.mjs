function addProofs(generated) {
  const lines = [];
  const steps = new Map();
  const input = generated.split("\n");
  let name = "";
  for (const [position, line] of input.entries()) {
    if (/^(?:method|function|lemma|datatype|type)\b/.test(line))
      name = line.match(/^method (\w+)\(/)?.[1] ?? "";
    const field = name.startsWith("read_") ? name.slice(5) : "";
    const shape = entries.find((entry) => entry.name === field)?.type;
    const collection = shape && (shape.vec || shape.array);
    if (
      name === "readUnsigned" &&
      line.trim() === "return RawUnsigned(0, (at + width), value);"
    )
      lines.push(
        "  assert 0 <= value < Pow256(width) by { LittleEndianRange(data, at, width); }",
      );
    if (collection && /^\s*var r := /.test(line)) {
      const child = intern(shape.vec ?? shape.array[0]);
      const temporary = line.match(
        /^\s*var r := ([A-Za-z_][A-Za-z_0-9']*);$/,
      )?.[1];
      const declaration = temporary ? input[position - 1] : line;
      if (!declaration?.includes(`:= read_${child}(data, cursor, used,`))
        throw new Error(`Unrecognized generated child read in ${name}`);
      steps.set(field, (steps.get(field) ?? 0) + 1);
      lines.push(line);
      lines.push(
        `    assert Rest_${field}(data, cursor, used, depth + 1, count - i, values) == (if r.error != 0 then ${rt(field)}(r.error, r.at, r.nodes, []) else Rest_${field}(data, r.at, r.nodes, depth + 1, count - i - 1, values + [r.value])) by { reveal Rest_${field}(); }`,
      );
      continue;
    }
    const returned = line.match(/^(\s*)return (.+);$/);
    if (returned && (field || name === "decodeJupiterBytes")) {
      const target = field
        ? `Spec_${field}(data, at, nodes, depth)`
        : "DecodeSpec(data)";
      const reveal = field ? `Spec_${field}` : "DecodeSpec";
      lines.push(
        `${returned[1]}assert ${returned[2]} == ${target} by { reveal ${reveal}(); ${collection ? `reveal Rest_${field}();` : ""} }`,
      );
    }
    lines.push(line);
  }
  for (const { type, name } of entries) {
    if ((type.vec || type.array) && steps.get(name) !== 1)
      throw new Error(`Expected one generated sequence step in ${name}`);
  }
  return `${lines.join("\n")}\n${semantics}`;
}
