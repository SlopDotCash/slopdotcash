/**
 * Snapshots the D1 project registry into a browser-safe static module plus
 * its append-only revision history. The live registry is served by
 * GET /api/v1/projects and GET /api/v1/project-revisions; sync mode downloads
 * both and check mode proves the committed snapshot is canonical, matches the
 * newest revision of every project, and that every active project carries
 * the content its generated skills need.
 */

import { randomUUID } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  assertHistoricalProjectDefinition,
  assertProjectRegistry,
} from "../src/lib/project-schema.mjs";
import { sha256Hex as sha256 } from "./sha256.mjs";

const REPOSITORY_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_PATH = resolve(
  REPOSITORY_ROOT,
  "src/lib/project-registry.generated.mjs",
);
const REVISIONS_PATH = resolve(
  REPOSITORY_ROOT,
  "src/lib/project-revisions.generated.json",
);
const DEFAULT_API_ORIGIN = "https://slop.cash";
const MAX_REGISTRY_BYTES = 4 * 1024 * 1024;
const FETCH_TIMEOUT_MS = 30_000;

/**
 * Project skills are generated from the manifest and the reviewed template,
 * so an active project must carry complete skill content.
 */
function assertActiveSkillContent(definitions) {
  for (const definition of definitions) {
    if (definition.status === "active" && definition.contribution === undefined)
      throw new TypeError(
        `Active project ${definition.id} has no generated-skill content`,
      );
  }
}

/** A canonical UTC timestamp, or null for a snapshot no sync wrote. */
function assertSyncedAt(value) {
  if (
    value !== null &&
    (typeof value !== "string" ||
      Number.isNaN(Date.parse(value)) ||
      new Date(value).toISOString() !== value)
  )
    throw new TypeError("Project registry sync time is not a UTC timestamp");
  return value;
}

/**
 * Renders the snapshot module. `syncedAt` records when projects:sync read
 * D1; the site publishes a synced snapshot as the last good registry that
 * pages show, with a stale label, when the live read fails (PRD section 9).
 */
export async function renderProjectRegistry(values, syncedAt = null) {
  assertSyncedAt(syncedAt);
  const definitions = [...assertProjectRegistry(values)].sort((left, right) =>
    left.id.localeCompare(right.id),
  );
  assertActiveSkillContent(definitions);
  const encodedDefinitions = JSON.stringify(definitions)
    .replaceAll("\\", "\\\\")
    .replaceAll("'", "\\'")
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029");
  return `/** Generated by scripts/sync-project-registry.mjs from the D1 project registry; do not edit by hand. */\n\nexport const RAW_PROJECT_DEFINITIONS = JSON.parse(\n  '${encodedDefinitions}',\n);\n\n/** When projects:sync read D1; null when no sync wrote this snapshot. */\nexport const PROJECT_REGISTRY_SYNCED_AT = ${JSON.stringify(syncedAt)};\n`;
}

class RegistrySnapshotChangedError extends TypeError {}

/**
 * Validates the revision history and proves each current manifest is the
 * newest revision. Funding records bind a manifest SHA-256 from this list.
 */
export function renderProjectRevisions(revisions, definitions) {
  if (!Array.isArray(revisions) || revisions.length > 10_000) {
    throw new TypeError("project revisions must be a bounded array");
  }
  const latest = new Map();
  const rows = revisions.map((entry) => {
    if (
      entry === null ||
      typeof entry !== "object" ||
      Object.keys(entry).sort().join(",") !==
        "createdAt,manifest,manifestSha256,projectId,reason,revision"
    ) {
      throw new TypeError("project revision has an unexpected shape");
    }
    const manifest = assertHistoricalProjectDefinition(entry.manifest);
    const previous = latest.get(entry.projectId) ?? 0;
    if (
      manifest.id !== entry.projectId ||
      entry.revision !== previous + 1 ||
      sha256(JSON.stringify(manifest)) !== entry.manifestSha256
    ) {
      throw new TypeError(
        `project revision ${entry.projectId}@${entry.revision} is out of order or does not match its digest`,
      );
    }
    latest.set(entry.projectId, entry.revision);
    return {
      projectId: entry.projectId,
      revision: entry.revision,
      manifestSha256: entry.manifestSha256,
      reason: entry.reason,
      createdAt: entry.createdAt,
      manifest,
    };
  });
  for (const definition of definitions) {
    const newest = rows.findLast((row) => row.projectId === definition.id);
    if (
      newest?.manifestSha256 !== sha256(JSON.stringify(definition)) &&
      !restrictionOf(newest?.manifest, definition)
    ) {
      throw new RegistrySnapshotChangedError(
        `project ${definition.id} does not match its newest revision`,
      );
    }
  }
  if (latest.size !== definitions.length) {
    throw new RegistrySnapshotChangedError(
      "project revisions name a project that is not listed",
    );
  }
  return `${JSON.stringify(rows, null, 2)}\n`;
}

/** The target origin predates the registry API; its first deploy adds it. */
export class RegistryNotDeployedError extends Error {}

async function fetchJson(url) {
  const parsed = new URL(url);
  if (
    parsed.protocol !== "https:" &&
    !(parsed.protocol === "http:" && parsed.hostname === "127.0.0.1")
  ) {
    throw new TypeError("Project registry URL must use HTTPS");
  }
  const response = await fetch(parsed, {
    headers: { accept: "application/json" },
    redirect: "error",
    signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
  });
  // Every registry API response carries its contract header. A 404 without
  // it means the environment does not run the registry API yet.
  if (
    response.status === 404 &&
    !response.headers.has("x-slop-project-api-contract")
  ) {
    throw new RegistryNotDeployedError(parsed.origin);
  }
  if (!response.ok) {
    throw new Error(`${parsed.pathname} returned HTTP ${response.status}`);
  }
  const text = await response.text();
  if (Buffer.byteLength(text) > MAX_REGISTRY_BYTES) {
    throw new Error(`${parsed.pathname} exceeds the size limit`);
  }
  return JSON.parse(text);
}

async function fetchRegistryPair(origin, snapshot) {
  const projectsUrl = new URL("/api/v1/projects", origin);
  const revisionsUrl = new URL("/api/v1/project-revisions", origin);
  if (snapshot !== undefined) {
    projectsUrl.searchParams.set("snapshot", snapshot);
    revisionsUrl.searchParams.set("snapshot", snapshot);
  }
  const [registry, history] = await Promise.all([
    fetchJson(projectsUrl),
    fetchJson(revisionsUrl),
  ]);
  // An origin that predates enforcement (PRD ADM-06) omits restrictions.
  const restrictions = registry?.restrictions ?? [];
  if (
    registry?.schemaVersion !== "1" ||
    !Array.isArray(registry.projects) ||
    !Array.isArray(restrictions) ||
    Object.keys(registry).some(
      (key) => !["schemaVersion", "projects", "restrictions"].includes(key),
    ) ||
    history?.schemaVersion !== "1" ||
    !Array.isArray(history.revisions) ||
    Object.keys(history).length !== 2
  ) {
    throw new TypeError("Project registry response has an unexpected shape");
  }
  const withheld = restrictionsPending(registry.projects, restrictions);
  return {
    projects: registry.projects.map((project) =>
      withheld.includes(project.id) ? restricted(project) : project,
    ),
    revisions: history.revisions,
    withheld,
  };
}

export async function fetchProjectRegistry(origin = DEFAULT_API_ORIGIN) {
  return fetchRegistryPair(origin);
}

/** Only snapshot publication needs the current manifests bound to history. */
async function fetchConsistentRegistry(origin) {
  for (let attempt = 0; ; attempt++) {
    let registry;
    try {
      registry = await fetchRegistryPair(
        origin,
        attempt === 0 ? undefined : randomUUID(),
      );
    } catch (error) {
      // A retry follows a successful API read, so a missing route is not
      // the first-deployment case that permits the committed bootstrap.
      if (attempt > 0 && error instanceof RegistryNotDeployedError)
        throw new Error(
          "Project registry API disappeared during synchronization",
        );
      throw error;
    }
    try {
      renderProjectRevisions(
        registry.revisions,
        assertProjectRegistry(registry.projects),
      );
      return registry;
    } catch (error) {
      // Independently cached reads can straddle an owner publication. Read
      // both again with fresh cache keys, but never accept an unbound pair.
      // Invalid rows and digests still fail without a retry.
      if (!(error instanceof RegistrySnapshotChangedError) || attempt >= 2)
        throw error;
    }
  }
}

/** The manifest with the paused, retired restriction applied. */
function restricted(project) {
  return { ...project, status: "paused", listingTier: "retired" };
}

/**
 * True when the definition is the newest revision with only the paused,
 * retired restriction applied. That snapshot is stricter than the registry,
 * never looser, so check mode accepts it without the restriction list.
 */
function restrictionOf(manifest, definition) {
  return (
    manifest !== undefined &&
    definition.status === "paused" &&
    definition.listingTier === "retired" &&
    JSON.stringify(restricted(manifest)) === JSON.stringify(definition)
  );
}

/**
 * A quarantined or banned project must already be paused and retired in its
 * newest revision; otherwise ingestion could still collect it. A project whose
 * paused, retired revision is still pending keeps its manifest and revisions
 * in the snapshot, because history lookups resolve through it, but the
 * snapshot applies the restriction at once, as the browser does. No
 * collection, listing, or skill step serves it. The admin appends the pending
 * revision at /admin, and the next sync stores that revision unchanged.
 */
function restrictionsPending(projects, restrictions) {
  const withheld = [];
  for (const restriction of restrictions) {
    const project = projects.find(
      (entry) => entry?.id === restriction?.projectId,
    );
    if (
      project === undefined ||
      !["quarantined", "banned"].includes(restriction.state)
    )
      throw new TypeError("Project restriction has an unexpected shape");
    if (project.status !== "paused" || project.listingTier !== "retired")
      withheld.push(project.id);
  }
  return withheld;
}

async function committedSnapshot() {
  const module = await import(
    `${pathToFileURL(OUTPUT_PATH).href}?check=${Date.now()}`
  );
  return {
    definitions: module.RAW_PROJECT_DEFINITIONS,
    syncedAt: module.PROJECT_REGISTRY_SYNCED_AT,
  };
}

export async function syncProjectRegistry(checkOnly = false) {
  if (checkOnly) {
    const { definitions, syncedAt } = await committedSnapshot();
    const expected = await renderProjectRegistry(definitions, syncedAt);
    const revisionsText = await readFile(REVISIONS_PATH, "utf8");
    if (
      (await readFile(OUTPUT_PATH, "utf8")) !== expected ||
      renderProjectRevisions(JSON.parse(revisionsText), definitions) !==
        revisionsText
    ) {
      throw new Error(
        "Project registry snapshot is not canonical; run bun run projects:sync",
      );
    }
    return false;
  }
  const origin = process.env.SLOP_API_ORIGIN || DEFAULT_API_ORIGIN;
  let registry;
  try {
    registry = await fetchConsistentRegistry(origin);
  } catch (error) {
    // Only the first rollout reaches this: the build that deploys the API
    // cannot read it yet, so it publishes the committed snapshot. Once the
    // API answers, every failure fails the build.
    if (!(error instanceof RegistryNotDeployedError)) throw error;
    process.stdout.write(
      `::notice::${origin} does not serve the project registry API yet; publishing the committed snapshot\n`,
    );
    return false;
  }
  const { projects, revisions, withheld } = registry;
  for (const projectId of withheld)
    process.stdout.write(
      `::warning::Project ${projectId} is restricted but its paused, retired revision is pending; the snapshot stores it paused and retired until an admin appends that revision at /admin\n`,
    );
  const rendered = await renderProjectRegistry(
    projects,
    new Date().toISOString(),
  );
  const renderedRevisions = renderProjectRevisions(
    revisions,
    assertProjectRegistry(projects),
  );
  await writeFile(OUTPUT_PATH, rendered, "utf8");
  await writeFile(REVISIONS_PATH, renderedRevisions, "utf8");
  return true;
}

if (import.meta.main) {
  try {
    const values = process.argv.slice(2);
    if (values.some((value) => value !== "--check") || values.length > 1) {
      throw new TypeError("Usage: sync-project-registry.mjs [--check]");
    }
    const checkOnly = values[0] === "--check";
    const synchronized = await syncProjectRegistry(checkOnly);
    process.stdout.write(
      checkOnly
        ? "[Slop] project registry snapshot is valid\n"
        : synchronized
          ? "[Slop] synchronized project registry from D1\n"
          : "[Slop] kept the committed project registry snapshot\n",
    );
  } catch (error) {
    // error-policy:J1 generator process boundary.
    process.stderr.write(
      `[Slop] project registry refused: ${error instanceof Error ? error.message : "unknown error"}\n`,
    );
    process.exitCode = 1;
  }
}
