/**
 * Snapshots the D1 project registry into a browser-safe static module plus
 * its append-only revision history. The live registry is served by
 * GET /api/v1/projects and GET /api/v1/project-revisions; sync mode downloads
 * both and check mode proves the committed snapshot is canonical, matches the
 * newest revision of every project, and names only skills in this tree.
 */

import { createHash } from "node:crypto";
import { access, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  assertHistoricalProjectDefinition,
  assertProjectRegistry,
} from "../src/lib/project-schema.mjs";

const REPOSITORY_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_PATH = resolve(
  REPOSITORY_ROOT,
  "src/lib/project-registry.generated.mjs",
);
const REVISIONS_PATH = resolve(
  REPOSITORY_ROOT,
  "src/lib/project-revisions.generated.json",
);
const DEFAULT_API_ORIGIN = "https://slop.cash";
const MAX_REGISTRY_BYTES = 4 * 1024 * 1024;
const FETCH_TIMEOUT_MS = 30_000;

/** An active project must name skills that exist in this reviewed tree. */
async function assertPublishedSkillsExist(definitions) {
  for (const definition of definitions) {
    if (definition.status !== "active") continue;
    for (const skillPath of [
      definition.skill.sourcePath,
      definition.reviewSkill.sourcePath,
    ]) {
      try {
        await access(resolve(REPOSITORY_ROOT, skillPath, "SKILL.md"));
      } catch (error) {
        throw new TypeError(
          `Project ${definition.id} references a missing skill: ${skillPath}`,
          { cause: error },
        );
      }
    }
  }
}

export async function renderProjectRegistry(values) {
  const definitions = [...assertProjectRegistry(values)].sort((left, right) =>
    left.id.localeCompare(right.id),
  );
  await assertPublishedSkillsExist(definitions);
  const encodedDefinitions = JSON.stringify(definitions)
    .replaceAll("\\", "\\\\")
    .replaceAll("'", "\\'")
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029");
  return `/** Generated by scripts/sync-project-registry.mjs from the D1 project registry; do not edit by hand. */\n\nexport const RAW_PROJECT_DEFINITIONS = JSON.parse(\n  '${encodedDefinitions}',\n);\n`;
}

function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

/**
 * Validates the revision history and proves each current manifest is the
 * newest revision. Funding records bind a manifest SHA-256 from this list.
 */
export function renderProjectRevisions(revisions, definitions) {
  if (!Array.isArray(revisions) || revisions.length > 10_000) {
    throw new TypeError("project revisions must be a bounded array");
  }
  const latest = new Map();
  const rows = revisions.map((entry) => {
    if (
      entry === null ||
      typeof entry !== "object" ||
      Object.keys(entry).sort().join(",") !==
        "createdAt,manifest,manifestSha256,projectId,reason,revision"
    ) {
      throw new TypeError("project revision has an unexpected shape");
    }
    const manifest = assertHistoricalProjectDefinition(entry.manifest);
    const previous = latest.get(entry.projectId) ?? 0;
    if (
      manifest.id !== entry.projectId ||
      entry.revision !== previous + 1 ||
      sha256(JSON.stringify(manifest)) !== entry.manifestSha256
    ) {
      throw new TypeError(
        `project revision ${entry.projectId}@${entry.revision} is out of order or does not match its digest`,
      );
    }
    latest.set(entry.projectId, entry.revision);
    return {
      projectId: entry.projectId,
      revision: entry.revision,
      manifestSha256: entry.manifestSha256,
      reason: entry.reason,
      createdAt: entry.createdAt,
      manifest,
    };
  });
  for (const definition of definitions) {
    const newest = rows.findLast((row) => row.projectId === definition.id);
    if (newest?.manifestSha256 !== sha256(JSON.stringify(definition))) {
      throw new TypeError(
        `project ${definition.id} does not match its newest revision`,
      );
    }
  }
  if (latest.size !== definitions.length) {
    throw new TypeError("project revisions name a project that is not listed");
  }
  return `${JSON.stringify(rows, null, 2)}\n`;
}

/** The target origin predates the registry API; its first deploy adds it. */
export class RegistryNotDeployedError extends Error {}

async function fetchJson(url) {
  const parsed = new URL(url);
  if (
    parsed.protocol !== "https:" &&
    !(parsed.protocol === "http:" && parsed.hostname === "127.0.0.1")
  ) {
    throw new TypeError("Project registry URL must use HTTPS");
  }
  const response = await fetch(parsed, {
    headers: { accept: "application/json" },
    redirect: "error",
    signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
  });
  // Every registry API response carries its contract header. A 404 without
  // it means the environment does not run the registry API yet.
  if (
    response.status === 404 &&
    !response.headers.has("x-slop-project-api-contract")
  ) {
    throw new RegistryNotDeployedError(parsed.origin);
  }
  if (!response.ok) {
    throw new Error(`${parsed.pathname} returned HTTP ${response.status}`);
  }
  const text = await response.text();
  if (Buffer.byteLength(text) > MAX_REGISTRY_BYTES) {
    throw new Error(`${parsed.pathname} exceeds the size limit`);
  }
  return JSON.parse(text);
}

export async function fetchProjectRegistry(origin = DEFAULT_API_ORIGIN) {
  const [registry, history] = await Promise.all([
    fetchJson(new URL("/api/v1/projects", origin)),
    fetchJson(new URL("/api/v1/project-revisions", origin)),
  ]);
  if (
    registry?.schemaVersion !== "1" ||
    !Array.isArray(registry.projects) ||
    Object.keys(registry).length !== 2 ||
    history?.schemaVersion !== "1" ||
    !Array.isArray(history.revisions) ||
    Object.keys(history).length !== 2
  ) {
    throw new TypeError("Project registry response has an unexpected shape");
  }
  return { projects: registry.projects, revisions: history.revisions };
}

async function committedDefinitions() {
  const module = await import(
    `${pathToFileURL(OUTPUT_PATH).href}?check=${Date.now()}`
  );
  return module.RAW_PROJECT_DEFINITIONS;
}

export async function syncProjectRegistry(checkOnly = false) {
  if (checkOnly) {
    const definitions = await committedDefinitions();
    const expected = await renderProjectRegistry(definitions);
    const revisionsText = await readFile(REVISIONS_PATH, "utf8");
    if (
      (await readFile(OUTPUT_PATH, "utf8")) !== expected ||
      renderProjectRevisions(JSON.parse(revisionsText), definitions) !==
        revisionsText
    ) {
      throw new Error(
        "Project registry snapshot is not canonical; run bun run projects:sync",
      );
    }
    return false;
  }
  const origin = process.env.SLOP_API_ORIGIN || DEFAULT_API_ORIGIN;
  let registry;
  try {
    registry = await fetchProjectRegistry(origin);
  } catch (error) {
    // Only the first rollout reaches this: the build that deploys the API
    // cannot read it yet, so it publishes the committed snapshot. Once the
    // API answers, every failure fails the build.
    if (!(error instanceof RegistryNotDeployedError)) throw error;
    process.stdout.write(
      `::notice::${origin} does not serve the project registry API yet; publishing the committed snapshot\n`,
    );
    return false;
  }
  const { projects, revisions } = registry;
  const rendered = await renderProjectRegistry(projects);
  const renderedRevisions = renderProjectRevisions(
    revisions,
    assertProjectRegistry(projects),
  );
  await writeFile(OUTPUT_PATH, rendered, "utf8");
  await writeFile(REVISIONS_PATH, renderedRevisions, "utf8");
  return true;
}

if (import.meta.main) {
  try {
    const values = process.argv.slice(2);
    if (values.some((value) => value !== "--check") || values.length > 1) {
      throw new TypeError("Usage: sync-project-registry.mjs [--check]");
    }
    const checkOnly = values[0] === "--check";
    const synchronized = await syncProjectRegistry(checkOnly);
    process.stdout.write(
      checkOnly
        ? "[Slop] project registry snapshot is valid\n"
        : synchronized
          ? "[Slop] synchronized project registry from D1\n"
          : "[Slop] kept the committed project registry snapshot\n",
    );
  } catch (error) {
    // error-policy:J1 generator process boundary.
    process.stderr.write(
      `[Slop] project registry refused: ${error instanceof Error ? error.message : "unknown error"}\n`,
    );
    process.exitCode = 1;
  }
}
