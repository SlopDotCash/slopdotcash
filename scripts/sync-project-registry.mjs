/**
 * Discovers schema-valid project folders and emits the browser-safe static
 * import registry. Check mode lets CI prove a project PR regenerated the index
 * without executing project-supplied code.
 */

import { access, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  assertProjectDefinition,
  assertProjectRegistry,
} from "../src/lib/project-schema.mjs";

const REPOSITORY_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PROJECTS_ROOT = resolve(REPOSITORY_ROOT, "projects");
const OUTPUT_PATH = resolve(
  REPOSITORY_ROOT,
  "src/lib/project-registry.generated.mjs",
);

export async function renderProjectRegistry() {
  const entries = await readdir(PROJECTS_ROOT, { withFileTypes: true });
  const directories = entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const definitions = [];
  for (const directory of directories) {
    if (!/^[a-z0-9](?:[a-z0-9-]{0,46}[a-z0-9])?$/u.test(directory)) {
      throw new TypeError(`Project directory is not canonical: ${directory}`);
    }
    const source = await readFile(
      resolve(PROJECTS_ROOT, directory, "project.json"),
      "utf8",
    );
    let definition;
    try {
      definition = JSON.parse(source);
    } catch (error) {
      throw new TypeError(
        `projects/${directory}/project.json is invalid JSON`,
        {
          cause: error,
        },
      );
    }
    if (definition.id !== directory) {
      throw new TypeError(
        `Project ${definition.id ?? "<missing>"} is in the wrong directory`,
      );
    }
    assertProjectDefinition(definition);
    for (const skillPath of [
      definition.skill?.sourcePath,
      definition.reviewSkill?.sourcePath,
    ]) {
      if (typeof skillPath !== "string") continue;
      try {
        await access(resolve(REPOSITORY_ROOT, skillPath, "SKILL.md"));
      } catch (error) {
        throw new TypeError(
          `Project ${directory} references a missing skill: ${skillPath}`,
          {
            cause: error,
          },
        );
      }
    }
    definitions.push(definition);
  }
  assertProjectRegistry(definitions);
  const imports = directories.map((directory, index) => {
    const source = `../../projects/${directory}/project.json`;
    const singleLine = `import project${index} from "${source}" with { type: "json" };`;
    return singleLine.length <= 80
      ? singleLine
      : `import project${index} from "${source}" with {\n  type: "json",\n};`;
  });
  return `/** Generated by scripts/sync-project-registry.mjs; do not edit by hand. */\n\n${imports.join("\n")}\n\nexport const RAW_PROJECT_DEFINITIONS = [${directories.map((_, index) => `project${index}`).join(", ")}];\n`;
}

export async function syncProjectRegistry(checkOnly = false) {
  const expected = await renderProjectRegistry();
  if (checkOnly) {
    const current = await readFile(OUTPUT_PATH, "utf8");
    if (current !== expected) {
      throw new Error("Project registry is stale; run bun run projects:sync");
    }
    return false;
  }
  await writeFile(OUTPUT_PATH, expected, "utf8");
  return true;
}

if (import.meta.main) {
  try {
    const values = process.argv.slice(2);
    if (values.some((value) => value !== "--check") || values.length > 1) {
      throw new TypeError("Usage: sync-project-registry.mjs [--check]");
    }
    const checkOnly = values[0] === "--check";
    await syncProjectRegistry(checkOnly);
    process.stdout.write(
      checkOnly
        ? "[Slop] project registry is current\n"
        : "[Slop] synchronized project registry\n",
    );
  } catch (error) {
    // error-policy:J1 generator process boundary.
    process.stderr.write(
      `[Slop] project registry refused: ${error instanceof Error ? error.message : "unknown error"}\n`,
    );
    process.exitCode = 1;
  }
}
