#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "brand/tokens.json");
const outputPath = resolve(root, "src/brand-tokens.css");
const check = process.argv.includes("--check");

const tokens = JSON.parse(await readFile(sourcePath, "utf8"));
const lines = ["/* Generated by scripts/sync-brand-tokens.mjs. */", ":root {"];
for (const [group, values] of Object.entries(tokens)) {
  for (const [name, value] of Object.entries(values)) {
    const kebab = name.replaceAll(/([a-z0-9])([A-Z])/gu, "$1-$2").toLowerCase();
    const property = `--brand-${group}-${kebab}`;
    const declaration = `  ${property}: ${value};`;
    if (declaration.length > 80) {
      lines.push(`  ${property}:`, `    ${value};`);
    } else {
      lines.push(declaration);
    }
  }
}
lines.push("}", "");
const expected = lines.join("\n");

if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== expected) {
    throw new Error("Brand tokens are stale; run bun run brand:sync");
  }
} else {
  await writeFile(outputPath, expected);
}
